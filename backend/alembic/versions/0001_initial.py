def _comment(target: str, text: str) -> None:
    """
    Attach a comment to a table or column.

    Comments are static constants of this migration; quotes are escaped
    anyway so the statement stays valid if one is added.

    :param target: ``TABLE name`` or ``COLUMN table.column``.
    :param text: Comment text.
    """
    escaped = text.replace("'", "''")
    op.execute(f"COMMENT ON {target} IS '{escaped}'")


