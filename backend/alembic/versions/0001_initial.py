def _now(name: str, nullable: bool = False) -> sa.Column:
    """
    Build a ``timestamptz`` column defaulting to ``now()``.

    :param name: Column name.
    :param nullable: Whether NULL is allowed.
    :returns: The column.
    """
    return sa.Column(
        name,
        sa.DateTime(timezone=True),
        server_default=sa.func.now(),
        nullable=nullable,
    )


